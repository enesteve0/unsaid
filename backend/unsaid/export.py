"""Deliverables: description and caption tracks, a text alternative, and editor markers."""

from __future__ import annotations

import html
from collections.abc import Iterable
from fractions import Fraction

from .schemas import Cue, Word


def vtt_text(text: str) -> str:
    """Cue text as WebVTT requires: & < > escaped, on one line, and no "-->" that would end the cue early."""
    return " ".join(html.escape(text, quote=False).split()).replace("--&gt;", "→")


def timestamp(seconds: float, sep: str = ".") -> str:
    ms = round(max(seconds, 0) * 1000)
    h, rem = divmod(ms, 3_600_000)
    m, rem = divmod(rem, 60_000)
    s, ms = divmod(rem, 1000)
    return f"{h:02d}:{m:02d}:{s:02d}{sep}{ms:03d}"


def descriptions_vtt(cues: Iterable[Cue]) -> str:
    """WebVTT for `<track kind="descriptions">`. Extended cues (no silence long enough) carry a NOTE and keep a
    short window so players that pause for descriptions know to stop the video."""
    lines = [
        "WEBVTT",
        "",
        "NOTE Audio descriptions generated by Unsaid. Extended cues need the player to pause.",
        "",
    ]
    for cue in sorted(cues, key=lambda c: c.start):
        if not cue.published:
            continue
        if cue.extended:
            lines += [f"NOTE extended description {cue.id}", ""]
        lines += [
            cue.id,
            f"{timestamp(cue.start)} --> {timestamp(max(cue.end, cue.start + 0.5))}",
            vtt_text(cue.text),
            "",
        ]
    return "\n".join(lines)


def _caption_chunks(
    words: list[Word], max_chars: int = 84, max_seconds: float = 6.0
) -> list[tuple[float, float, str]]:
    chunks: list[tuple[float, float, str]] = []
    current: list[Word] = []
    for w in words:
        text = " ".join(x.text.strip() for x in [*current, w])
        too_long = len(text) > max_chars or (current and w.end - current[0].start > max_seconds)
        if current and too_long:
            chunks.append((current[0].start, current[-1].end, " ".join(x.text.strip() for x in current)))
            current = []
        current.append(w)
        if w.text.rstrip().endswith((".", "?", "!")) and len(" ".join(x.text for x in current)) > 30:
            chunks.append((current[0].start, current[-1].end, " ".join(x.text.strip() for x in current)))
            current = []
    if current:
        chunks.append((current[0].start, current[-1].end, " ".join(x.text.strip() for x in current)))
    return chunks


def captions_vtt(words: list[Word]) -> str:
    lines = ["WEBVTT", ""]
    for i, (start, end, text) in enumerate(_caption_chunks(words), start=1):
        lines += [f"c{i}", f"{timestamp(start)} --> {timestamp(end)}", vtt_text(text), ""]
    return "\n".join(lines)


def captions_srt(words: list[Word]) -> str:
    lines: list[str] = []
    for i, (start, end, text) in enumerate(_caption_chunks(words), start=1):
        lines += [str(i), f"{timestamp(start, ',')} --> {timestamp(end, ',')}", " ".join(text.split()), ""]
    return "\n".join(lines)


def transcript_html(words: list[Word], cues: Iterable[Cue], title: str) -> str:
    """Text alternative for the whole video: speech with the descriptions inline, in time order."""
    items: list[tuple[float, str]] = [
        (start, f"<p>{html.escape(text)}</p>")
        for start, _, text in _caption_chunks(words, max_chars=400, max_seconds=30)
    ]
    items += [
        (c.start, f'<p class="description"><strong>Description:</strong> {html.escape(c.text)}</p>')
        for c in cues
        if c.published
    ]
    body = "\n".join(markup for _, markup in sorted(items, key=lambda x: x[0]))
    return (
        f'<!doctype html><html lang="en"><head><meta charset="utf-8"><title>{html.escape(title)}: transcript '
        f"with descriptions</title></head><body><h1>{html.escape(title)}</h1>\n{body}\n</body></html>\n"
    )


def _rational(seconds: float, fps: float) -> str:
    frame = Fraction(1, max(1, round(fps or 25)))
    frames = round(seconds / frame)
    value = Fraction(frames) * frame
    return f"{value.numerator}/{value.denominator}s" if value.denominator != 1 else f"{value.numerator}s"


def fcpxml_markers(
    cues: Iterable[Cue], *, name: str, duration: float, fps: float, width: int, height: int
) -> str:
    """Final Cut Pro project with one marker per description, on a gap clip so it imports without media."""
    rate = max(1, round(fps or 25))
    markers = "\n".join(
        f'          <marker start="{_rational(c.start, rate)}" duration="{_rational(1 / rate, rate)}" '
        f'value="{html.escape(("[EXTENDED] " if c.extended else "") + c.text, quote=True)}"/>'
        for c in sorted(cues, key=lambda c: c.start)
        if c.published
    )
    total = _rational(duration, rate)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE fcpxml>
<fcpxml version="1.10">
  <resources>
    <format id="r1" name="FFVideoFormat{height}p{rate}" frameDuration="1/{rate}s" width="{width}" height="{height}"/>
  </resources>
  <library>
    <event name="Unsaid">
      <project name="{html.escape(name, quote=True)} (audio description)">
        <sequence format="r1" duration="{total}" tcStart="0s" tcFormat="NDF">
          <spine>
            <gap name="Descriptions" offset="0s" start="0s" duration="{total}">
{markers}
            </gap>
          </spine>
        </sequence>
      </project>
    </event>
  </library>
</fcpxml>
"""
